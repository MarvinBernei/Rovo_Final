// Formularverhalten des tatsächlich generierten Flows, ohne Browser oder Anbieter.
const fs = require('node:fs');
const assert = require('node:assert/strict');
const flow = JSON.parse(fs.readFileSync(require('node:path').join(__dirname, '../nodered/rovo_neu_flows.json'), 'utf8'));
const widget = flow.find(n => n.id === 'c8261020b3000012');
const script = widget.format.match(/<script>([\s\S]*?)<\/script>/)[1];
const component = new Function(script.replace('export default', 'return'))();
let checks = 0;
const check = (value, message) => {assert.ok(value, message);checks++};
const sent = [];
const vm = {send: packet => sent.push(packet)};
Object.assign(vm, component.data.call(vm));
Object.assign(vm, {bridgeFresh: true});
for (const [key, method] of Object.entries(component.methods)) vm[key] = method.bind(vm);
for (const [key, getter] of Object.entries(component.computed || {})) {
 if(key!=='bridgeFresh')Object.defineProperty(vm,key,{get:()=>getter.call(vm),configurable:true});
}
const incoming = payload => component.watch.msg.handler.call(vm, {payload});
const runtime = {
 llm: {model:'test-model',enabled:true,has_key:true},spotify:{client_id:'test-client',redirect_uri:'http://127.0.0.1:8888/callback',device_id:'test-device'},
 motion:{},audio:{},display:{},camera:{},limits:{pan:{},tilt:{}}
};
incoming({kind:'snapshot',bridge:{online:true},runtime});
check(vm.connectionModel==='test-model'&&vm.connectionClientId==='test-client','Gespeicherte öffentliche Felder laden');
check(vm.connectionKey===''&&vm.connectionConsent===false,'Key wird nicht geladen, neue Freigabe ausdrücklich');
vm.connectionModel='unsaved-model';
incoming({kind:'snapshot',bridge:{online:true},runtime});
check(vm.connectionModel==='unsaved-model','Snapshots überschreiben ungespeicherte Eingaben nicht');
vm.connectionKey='dummy-key';vm.connectionConsent=true;vm.connectionEnabled=true;
vm.connectionSaveLLM();
check(vm.connectionKey===''&&sent.at(-1).payload.data.apiKey==='dummy-key','Key nur im Auftrag, Feld sofort leeren');
check(sent.at(-1).payload.action==='llm.save'&&vm.connectionBusy,'Speichern angebunden');
incoming({kind:'integrations',action:'llm.save',ok:true,message:'Gespeichert'});
check(!vm.connectionBusy&&vm.connectionNotice==='Gespeichert','Antwort beendet Wartezustand');
vm.connectionStartLogin();
incoming({kind:'integrations',action:'spotify.login',ok:true,data:{auth_url:'https://accounts.spotify.com/authorize?state=test'}});
check(vm.connectionAuthUrl.startsWith('https://accounts.spotify.com/'),'Anmeldelink angezeigt');
vm.connectionCallback='http://127.0.0.1:8888/callback?code=dummy-code&state=test';
vm.connectionComplete();
check(vm.connectionCallback===''&&sent.at(-1).payload.action==='spotify.complete','Anmeldecode nach Senden gelöscht');
incoming({kind:'integrations',action:'spotify.complete',ok:true});
check(vm.connectionAuthUrl==='','Verbrauchter Anmeldelink gelöscht');
incoming({kind:'integrations',action:'spotify.devices',ok:true,data:{devices:[{id:'device-a',name:'Test'}]}});
check(vm.connectionDevices[0].id==='device-a','Geräteliste angebunden');
vm.connectionDevice='device-a';vm.connectionSend('spotify.select',{deviceId:vm.connectionDevice});
check(sent.at(-1).payload.data.deviceId==='device-a','Ausgewähltes Gerät gesendet');
incoming({kind:'integrations',action:'spotify.select',ok:true});
vm.connectionForgetLLM=true;vm.connectionRemove('llm.forget');
check(!vm.connectionForgetLLM&&sent.at(-1).payload.data.confirm===true,'Entfernen einmalig bestätigt');
incoming({kind:'integrations',action:'llm.forget',ok:true});
check(!vm.connectionEnabled&&!vm.connectionConsent,'Entfernter Anbieter im Formular deaktiviert');
const before=sent.length;vm.bridgeFresh=false;vm.connectionSend('llm.test');
check(sent.length===before,'Offline keine Anfrage');
vm.connectionAuthUrl='';incoming({kind:'integrations',action:'spotify.login',ok:true,data:{auth_url:'javascript:invalid'}});
check(vm.connectionAuthUrl==='','Fremdes Linkprotokoll abgewiesen');
vm.connectionBusy=false;
vm.connectionProfiles={openai:{model:'openai-model',models:['openai-model'],has_key:true},anthropic:{model:'claude-model',models:['claude-model'],has_key:true}};
vm.llmState={provider:'openai',model:'openai-model',enabled:true};
vm.connectionKey='dummy-openai';vm.connectionConsent=true;vm.connectionProvider='anthropic';
vm.connectionUseProvider();
check(vm.connectionKey===''&&!vm.connectionConsent&&!vm.connectionEnabled,'Anbieterwechsel entfernt Eingabekey und verlangt eigene Freigabe');
check(vm.connectionModel==='claude-model'&&vm.connectionModels[0]==='claude-model','Anbieterspezifische Modellauswahl');
check(!vm.connectionSelectionActive,'Anbieterwechsel im Formular aktiviert keine andere Cloud');
const selections=sent.length;vm.connectionModel='other-claude';
check(sent.length===selections&&vm.connectionModel==='other-claude','Modellauswahl sendet keinen Aktivierungsauftrag');
incoming({kind:'integrations',action:'llm.models',ok:true,data:{provider:'openai',models:['new-openai']}});
check(!vm.connectionModels.includes('new-openai'),'Katalogantwort eines anderen Anbieters vermischt Auswahl nicht');
incoming({kind:'integrations',action:'llm.models',ok:true,data:{provider:'anthropic',models:['new-claude']}});
check(vm.connectionModels.includes('new-claude')&&vm.connectionModel==='other-claude','Geladene Modelle ergänzen Auswahl ohne Überschreiben');
vm.bridgeFresh=true;vm.connectionBusy=false;vm.connectionConsent=true;vm.connectionEnabled=true;
vm.connectionSaveLLM();
check(sent.at(-1).payload.data.provider==='anthropic'&&sent.at(-1).payload.data.apiKey==='','Gespeicherter Key wird nur beim gewählten Anbieter verwendet');
vm.connectionBusy=false;vm.connectionKey='dummy-new-key';vm.connectionLoadModels();
check(vm.connectionKey===''&&sent.at(-1).payload.action==='llm.models'&&sent.at(-1).payload.data.provider==='anthropic','Modellliste mit neuem Key laden leert das Passwortfeld');
vm.bridgeFresh=true;vm.connectionBusy=true;vm.connectionCancel();
check(sent.at(-1).payload.action==='spotify.cancel','Abbruch auch während laufender Anmeldung möglich');
vm.connectionKey='dummy-key';vm.connectionCallback='dummy-code';component.unmounted.call(vm);
check(vm.connectionKey===''&&vm.connectionCallback==='','Felder bei Seitenwechsel leeren');
check(widget.storeOutMessages===false&&widget.resendOnRefresh===false,'Keine gespeicherten Eingaben oder Wiederholung im UI-Node');
console.log(`Verbindungsformular: ${checks} Prüfungen bestanden.`);
