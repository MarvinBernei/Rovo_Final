import { readFileSync } from 'node:fs';
const flow=JSON.parse(readFileSync(new URL('../nodered/rovo_neu_flows.json',import.meta.url),'utf8'));
const scripts=flow.filter(n=>n.type==='function').map(n=>({id:n.id,code:n.func}));
function run(scripts, nodes){
let checks=0;
const check=(value,message)=>{if(!value)throw new Error(message);checks++;};
const state=new Map(), sent=[];
const context={get:key=>state.get(key),set:(key,value)=>state.set(key,value)};
const node={send:value=>sent.push(value)};
const env={get:key=>key==='ROVO_API_TOKEN'?'x'.repeat(40):undefined};
const compile=id=>{const script=scripts.find(s=>s.id===id);check(!!script,id);return new Function('msg','node','env','flow',script.code);};
const prepare=compile('rovo-v5-prepare'), receive=compile('rovo-v5-result'), timeout=compile('rovo-v5-timeout');
const call=(fn,msg)=>fn(msg,node,env,context);
check(call(prepare,{payload:{type:'motion.home',data:{}}})===null,'Offline-Befehl gesperrt');
call(receive,{topic:'rovo/v1/availability',payload:{online:true,boot_id:'boot'}});
const snapshot={kind:'snapshot',bridge:{online:true,updated_at_utc:new Date().toISOString()}};
check(call(receive,{topic:'rovo/v1/status',payload:{boot_id:'boot',snapshot}})[0][0].payload===snapshot,'Status weitergeleitet');
const client={socketId:'client-A'};
const request=call(prepare,{payload:{type:'chat.send',data:{text:'Hallo'}},_client:client})[0];
const envelope=JSON.parse(request.payload);
check(request.topic==='rovo/v1/command','Befehlstopic');
check(request.retain===false,'Kein retained Befehl');
check(!request.headers,'Kein HTTP-Token auf MQTT');
check(envelope.boot_id==='boot'&&envelope.session==='client-A','Generation und Sitzung');
const answer=call(receive,{topic:'rovo/v1/reply',payload:{id:envelope.id,boot_id:'boot',result:{ok:true,message:'Hallo',reply:'Hallo',snapshot}}});
check(answer[0].every(packet=>packet._client===client),'Antwort nur an ursprünglichen Client');
check(answer[0].some(packet=>packet.payload.kind==='chat_response'),'Chatantwort');
check(call(receive,{topic:'rovo/v1/reply',payload:{id:envelope.id,boot_id:'boot',result:{ok:true}}})===null,'Doppelte Antwort verworfen');
check(call(receive,{topic:'rovo/v1/status',payload:{boot_id:'alt',snapshot}})===null,'Alte Generation verworfen');
check(call(prepare,{payload:{type:'shell',data:{}}})===null,'Nicht erlaubte Aktion gesperrt');
state.set('rovoPending',{old:{at:0,action:'chat.send',client}});
check(call(timeout,{})[0][0].payload.kind==='chat_response','Antwortfrist');
check(Object.keys(state.get('rovoPending')).length===0,'Abgelaufene Aufträge entfernt');
state.set('rovoLive',1);call(timeout,{});
check(state.get('rovoBoot')===null,'Veralteter Status sperrt Befehle');
const camera=compile('rovo-camera-prepare'), sanitize=compile('rovo-camera-sanitize');
const proxy=call(camera,{})[0];
check(proxy.url.endsWith('/api/v1/camera.jpg'),'Kamera separat HTTP');
check(proxy.headers.Authorization.startsWith('Bearer '),'Token nur im Proxy');
const clean=call(sanitize,{statusCode:200,headers:proxy.headers,payload:'JPEG'});
check(!clean.headers.Authorization&&clean.headers['Content-Type']==='image/jpeg','Token entfernt');
check(nodes.filter(n=>n.type==='mqtt out').length===1,'Ein Befehlspfad');
check(nodes.filter(n=>n.type==='ui-page').length===9,'Neun Seiten');
state.set('rovoBoot','boot');state.set('rovoLive',Date.now());
const runtimeRequest=JSON.parse(call(prepare,{payload:{action:'audio.configure',data:{speech_volume:40,speech_rate:1,music_volume:20}},_client:client})[0].payload);
const runtimeResponse=call(receive,{topic:'rovo/v1/reply',payload:{id:runtimeRequest.id,boot_id:'boot',result:{ok:true,message:'Übernommen',result:{status:'completed',data:{speech_volume_percent:40}}}}});
check(runtimeResponse[0][0].payload.data.speech_volume_percent===40,'Aktionsdaten erreichen Node-RED');
for(const action of ['llm.save','llm.test','llm.forget','llm.models','spotify.save','spotify.login','spotify.complete','spotify.cancel','spotify.test','spotify.devices','spotify.select','spotify.disconnect']){
 const data=action==='llm.save'?{apiKey:'dummy-key'}:{};
 const packet=call(prepare,{payload:{action,data},_client:client})[0];
 const request=JSON.parse(packet.payload);
 check(request.action===action&&packet.retain===false,'Verbindungsaktion erlaubt und nie retained: '+action);
 check(!JSON.stringify(state.get('rovoPending')).includes('dummy-key'),'Keine Credentials im Flow-Kontext');
 const reply=call(receive,{topic:'rovo/v1/reply',payload:{id:request.id,boot_id:'boot',result:{ok:true,message:'Verbindung geprüft',status:{llm:{has_key:true}},connection_data:{devices:[]}}}});
 check(reply[0].every(p=>p._client===client),'Verbindungsantwort bleibt clientgebunden');
 check(reply[0].some(p=>p.payload.kind==='integrations'&&p.payload.action===action&&p.payload.data.devices.length===0),'Verbindungsdaten erreichen Formular');
}
return checks;
}
console.log(`MQTT-Dashboard-JavaScript: ${run(scripts,flow)} Prüfungen bestanden.`);
